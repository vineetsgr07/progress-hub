/** Phone chip text. Custom frequencies keep their full name. */
export function frequencyFilterLabel(value: string, compact: boolean): string {
  if (!compact) return value
  return (
    taskCopy.frequencyShort[value as keyof typeof taskCopy.frequencyShort] ??
    value
  )
}
